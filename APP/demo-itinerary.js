export function ensureDemoItinerary(trip){
 if(trip.id!=='t1'){trip.itinerary??=[];return trip.itinerary;}
 if(trip.itinerarySeedVersion>=3)return trip.itinerary;
 const isSeed=e=>/^plan-[123]$|^demo-day\d+-\d+$/.test(e.id);
 const kept=(trip.itinerary||[]).filter(e=>!isSeed(e)||e.updated||e.done),added=[];
 for(let day=0;day<plans.length;day++){
  const date=new Date(trip.start+'T00:00:00Z');date.setUTCDate(date.getUTCDate()+day);
  const iso=date.toISOString().slice(0,10);if(iso>trip.end)continue;
  plans[day].forEach(([start,end,title,kind,location,note,source,place],index)=>{
   if(kept.some(e=>e.date===iso&&e.start&&e.end&&e.start<end&&start<e.end))return;
   added.push({id:`rich-day${day+1}-${index+1}`,date:iso,start,end,title,kind,location,note,source:source||'',place:place||'',done:false,creator:trip.owner});
  });
 }
 trip.itinerary=[...kept,...added].sort((a,b)=>a.date.localeCompare(b.date)||(a.start||'23:59').localeCompare(b.start||'23:59'));
 trip.itinerarySeedVersion=3;
 return trip.itinerary;
}
